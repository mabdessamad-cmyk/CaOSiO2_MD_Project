"""
Partial RDF analysis for CaO-SiO2 glass.

The input file is generated by:

    compute rdf all rdf 300 1 1 1 2 1 3 2 2 2 3 3 3

LAMMPS ordering:

    Si-Si, Si-O, Si-Ca, O-O, O-Ca, Ca-Ca

Each pair contributes:
    g(r), coordination(r)
"""

from pathlib import Path
import numpy as np


PAIR_CHANNELS = {
    "Si-Si": (2, 3),
    "Si-O":  (4, 5),
    "Si-Ca": (6, 7),
    "O-O":   (8, 9),
    "O-Ca":  (10, 11),
    "Ca-Ca": (12, 13),
}


class PartialRDF:
    """Analyze chemically resolved partial RDFs."""

    def __init__(self, filename):
        self.filename = Path(filename)
        self.r = None
        self.data = None

    def read(self):
        rows = []

        with self.filename.open() as fh:
            for line in fh:
                fields = line.split()

                if len(fields) != 14:
                    continue

                rows.append([float(x) for x in fields])

        if not rows:
            raise ValueError("No 14-column RDF rows found.")

        data = np.asarray(rows, dtype=float)

        if data.shape[1] != 14:
            raise ValueError(
                f"Expected 14 columns, found {data.shape[1]}."
            )

        self.data = data
        self.r = data[:, 1]

        return self

    def pair_rdf(self, pair):
        """Return r, g(r) for one chemical pair."""

        if pair not in PAIR_CHANNELS:
            raise KeyError(f"Unknown pair: {pair}")

        g_col, _ = PAIR_CHANNELS[pair]

        return self.r, self.data[:, g_col]

    def pair_coordination(self, pair):
        """Return r, coordination(r) for one chemical pair."""

        if pair not in PAIR_CHANNELS:
            raise KeyError(f"Unknown pair: {pair}")

        _, cn_col = PAIR_CHANNELS[pair]

        return self.r, self.data[:, cn_col]

    def peak(self, pair):
        """Return first/main RDF peak position and height."""

        r, g = self.pair_rdf(pair)

        i = int(np.argmax(g))

        return {
            "r": float(r[i]),
            "g": float(g[i]),
        }

    def first_minimum(self, pair):
        """
        Return the first local minimum after the principal RDF peak.
        """

        r, g = self.pair_rdf(pair)

        peak_index = int(np.argmax(g))

        for i in range(peak_index + 1, len(g) - 1):
            if g[i] <= g[i - 1] and g[i] <= g[i + 1]:
                return {
                    "r": float(r[i]),
                    "g": float(g[i]),
                }

        raise ValueError(f"No local minimum after peak for {pair}.")

    def report(self):
        """Return a compact structural RDF report."""

        if self.data is None:
            self.read()

        report = {}

        for pair in PAIR_CHANNELS:
            report[pair] = {
                "peak": self.peak(pair),
                "first_minimum": self.first_minimum(pair),
            }

        return report
